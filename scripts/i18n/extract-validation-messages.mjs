#!/usr/bin/env node
// The shared schemas (@abonten/validation) say what is wrong with a value
// in English: "Username must be at least 3 characters." They run in the
// browser, in the app and on the server, and have no translator of their
// own, so — like the sentences the database raises — the English sentence
// is the key. This collects every one into the `validation` namespace
// (a `${value}` becomes {0}, {1}, …) and generates the index the apps and
// the server use to find a message's key (packages/i18n/src/validation.ts).
//
//   node scripts/i18n/extract-validation-messages.mjs           # write
//   node scripts/i18n/extract-validation-messages.mjs --check   # CI
//
// The admin console's schemas (adminSchemas, weeklySchemas) are left out:
// the console is English.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");
const CATALOG = join(ROOT, "packages/i18n/messages/en/validation.json");
const INDEX = join(ROOT, "packages/i18n/src/validationIndex.generated.ts");
const CHECK = process.argv.includes("--check");

const STAFF_ONLY = [
  "packages/validation/src/adminSchemas.ts",
  "packages/validation/src/weeklySchemas.ts",
];

// The literal sweep already knows which strings read like words.
const out = join(mkdtempSync(join(tmpdir(), "abonten-validation-")), "f.json");
try {
  execFileSync(
    process.execPath,
    [
      join(HERE, "check-literals.mjs"),
      "--target",
      "shared",
      "--with-validation",
      "--json",
      out,
    ],
    { stdio: "ignore" },
  );
} catch {
  // exits 1 when it finds strings: that is what we are here to read
}
const found = JSON.parse(readFileSync(out, "utf8"));

const texts = new Set();
for (const [file, list] of Object.entries(found)) {
  if (!file.startsWith("packages/validation/src/")) continue;
  if (STAFF_ONLY.includes(file)) continue;
  for (const text of list) texts.add(text);
}

/** `{}` placeholders numbered, a literal <tag> quoted for ICU. */
function icu(text) {
  let n = 0;
  return text
    .replace(/<[^<>']*>/g, (tag) => `'${tag}'`)
    .replace(/\{\}/g, () => `{${n++}}`);
}

function slug(text) {
  const words = text
    .replace(/\{\}/g, " ")
    .replace(/[^A-Za-z0-9 ]+/g, " ")
    .trim()
    .split(/\s+/)
    .slice(0, 6);
  const key = words
    .map((w, i) =>
      i === 0
        ? w.charAt(0).toLowerCase() + w.slice(1)
        : w.charAt(0).toUpperCase() + w.slice(1).toLowerCase(),
    )
    .join("");
  return key || "message";
}

// Keys are stable: a sentence that is already in the catalog keeps its key.
let existing = {};
try {
  existing = JSON.parse(readFileSync(CATALOG, "utf8"));
} catch {
  existing = {};
}
const keyOf = new Map(Object.entries(existing).map(([k, v]) => [v, k]));
const used = new Set();
const catalog = {};
for (const text of [...texts].sort()) {
  const message = icu(text);
  let key = keyOf.get(message);
  if (!key || used.has(key)) {
    const base = slug(text);
    key = base;
    let i = 2;
    while (used.has(key) || (existing[key] && existing[key] !== message)) {
      key = `${base}${i++}`;
    }
  }
  used.add(key);
  catalog[key] = message;
}
const sorted = Object.fromEntries(
  Object.keys(catalog)
    .sort()
    .map((k) => [k, catalog[k]]),
);

const catalogText = `${JSON.stringify(sorted, null, 2)}\n`;
// Written the way the formatter leaves it (bare keys, trailing commas), so
// formatting on commit never makes the file look stale.
const indexLines = Object.entries(sorted).map(([key, text]) => {
  const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
  const line = `  ${name}: ${JSON.stringify(text)},`;
  return line.length <= 80 ? line : `  ${name}:\n    ${JSON.stringify(text)},`;
});
const indexText = `// Generated by scripts/i18n/extract-validation-messages.mjs — do not edit by hand.
// key → the English sentence @abonten/validation writes ({0}, {1} for values).

export const VALIDATION_SOURCE: Record<string, string> = {
${indexLines.join("\n")}
};
`;

if (CHECK) {
  let current = "";
  let currentIndex = "";
  try {
    current = readFileSync(CATALOG, "utf8");
    currentIndex = readFileSync(INDEX, "utf8");
  } catch {
    // missing files are stale files
  }
  const same =
    JSON.stringify(JSON.parse(current || "{}")) === JSON.stringify(sorted) &&
    currentIndex.replace(/\s+/g, "") === indexText.replace(/\s+/g, "");
  if (!same) {
    console.error(
      "validation catalog is stale: run node scripts/i18n/extract-validation-messages.mjs",
    );
    process.exit(1);
  }
  console.log(
    `validation catalog: ${Object.keys(sorted).length} messages, current.`,
  );
} else {
  writeFileSync(CATALOG, catalogText);
  writeFileSync(INDEX, indexText);
  console.log(
    `validation catalog: ${Object.keys(sorted).length} messages written.`,
  );
}
