#!/usr/bin/env node
// Generates packages/core/src/geo/countryData.ts: every ISO 3166-1 alpha-2
// country libphonenumber knows a dial code for, with its English name (from
// Node's ICU data) and flag emoji. Currency, time zone and address rules are
// NOT here — those are market configuration (the `market` table) or the
// curated map in packages/core/src/geo/countryDefaults.ts, never inferred
// from a dial code.
//
// Run: node scripts/gen-country-data.mjs   (commit the output)

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { getCountries, getCountryCallingCode } from "libphonenumber-js/min";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "packages/core/src/geo/countryData.ts");

const names = new Intl.DisplayNames(["en"], { type: "region" });

function flagFor(code) {
  return String.fromCodePoint(
    ...[...code.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  );
}

const rows = getCountries()
  .map((code) => {
    let name;
    try {
      name = names.of(code);
    } catch {
      name = undefined;
    }
    if (!name || name === code) return null;
    return {
      code,
      name,
      dialCode: `+${getCountryCallingCode(code)}`,
      flag: flagFor(code),
    };
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

const body = rows
  .map(
    (r) =>
      `  { code: ${JSON.stringify(r.code)}, name: ${JSON.stringify(r.name)}, dialCode: ${JSON.stringify(r.dialCode)}, flag: ${JSON.stringify(r.flag)} },`,
  )
  .join("\n");

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-country-data.mjs — do not edit by hand.
// ${rows.length} countries: ISO 3166-1 alpha-2 code, English short name (ICU),
// E.164 dial code (libphonenumber) and flag emoji.

export type CountryDatum = {
  code: string;
  name: string;
  dialCode: string;
  flag: string;
};

export const COUNTRY_DATA: readonly CountryDatum[] = [
${body}
];
`,
);

console.log(`wrote ${rows.length} countries to ${OUT}`);
