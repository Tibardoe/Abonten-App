#!/usr/bin/env node
// Generates packages/core/src/geo/countryData.ts: every ISO 3166-1 alpha-2
// country libphonenumber knows a dial code for, with its English name (from
// Node's ICU data) and flag emoji. Currency, time zone and address rules are
// NOT here — those are market configuration (the `market` table) or the
// curated map in packages/core/src/geo/countryDefaults.ts, never inferred
// from a dial code.
//
// Run: node scripts/gen-country-data.mjs   (commit the output)

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { getCountries, getCountryCallingCode } from "libphonenumber-js/min";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "packages/core/src/geo/countryData.ts");

const names = new Intl.DisplayNames(["en"], { type: "region" });

function flagFor(code) {
  return String.fromCodePoint(
    ...[...code.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  );
}

const rows = getCountries()
  .map((code) => {
    let name;
    try {
      name = names.of(code);
    } catch {
      name = undefined;
    }
    if (!name || name === code) return null;
    return {
      code,
      name,
      dialCode: `+${getCountryCallingCode(code)}`,
      flag: flagFor(code),
    };
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

const body = rows
  .map(
    (r) =>
      `  { code: ${JSON.stringify(r.code)}, name: ${JSON.stringify(r.name)}, dialCode: ${JSON.stringify(r.dialCode)}, flag: ${JSON.stringify(r.flag)} },`,
  )
  .join("\n");

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-country-data.mjs — do not edit by hand.
// ${rows.length} countries: ISO 3166-1 alpha-2 code, English short name (ICU),
// E.164 dial code (libphonenumber) and flag emoji.

export type CountryDatum = {
  code: string;
  name: string;
  dialCode: string;
  flag: string;
};

export const COUNTRY_DATA: readonly CountryDatum[] = [
${body}
];
`,
);

console.log(`wrote ${rows.length} countries to ${OUT}`);

// ── the same countries, named in each language the app speaks ──
//
// The phone-number country picker listed "Germany" to someone reading
// French. The names come from CLDR through Node's ICU, the same source as
// the English ones above, so nobody translates 245 country names by hand.
// Akan has names in CLDR too ("Gaana"). Portuguese uses the European forms
// the catalogs are written in ("Chéquia", not "Tchéquia").

const NAMES_OUT = join(ROOT, "packages/core/src/geo/countryNames.generated.ts");
const registry = JSON.parse(
  readFileSync(join(ROOT, "packages/i18n/src/locales.json"), "utf8"),
);
const ICU_TAG = { pt: "pt-PT" };
const blocks = [];
for (const locale of registry.order) {
  if (locale === "en") continue;
  const tag = ICU_TAG[locale] ?? locale;
  if (Intl.DisplayNames.supportedLocalesOf([tag]).length === 0) continue;
  const localized = new Intl.DisplayNames([tag], { type: "region" });
  const lines = rows
    .map((r) => {
      let name;
      try {
        name = localized.of(r.code);
      } catch {
        name = undefined;
      }
      // Same as English: nothing to add, the fallback says it.
      if (!name || name === r.code || name === r.name) return null;
      return `    ${r.code}: ${JSON.stringify(name)},`;
    })
    .filter(Boolean);
  blocks.push(`  ${locale}: {\n${lines.join("\n")}\n  },`);
}

writeFileSync(
  NAMES_OUT,
  `// GENERATED by scripts/gen-country-data.mjs — do not edit by hand.
// Country names in each language the app speaks (CLDR, through Node's ICU),
// where they differ from the English name in countryData.ts.

export const COUNTRY_NAMES: Readonly<
  Record<string, Readonly<Record<string, string>>>
> = {
${blocks.join("\n")}
};
`,
);

console.log(
  `wrote ${blocks.length} languages of country names to ${NAMES_OUT}`,
);
