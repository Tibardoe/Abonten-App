#!/usr/bin/env node
// Writes docs/admin/metrics.md from the metric registry in
// packages/core/src/admin/metricDefinitions.ts, so the glossary an operator
// reads and the definitions the console shows can never disagree. Run it
// after changing the registry:
//
//   npm run docs:metrics
//
// packages/core/src/admin/metricDefinitions.test.ts fails if the committed
// file is out of date, so a forgotten run is caught in CI rather than in
// someone's understanding of a number.

import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SOURCE = join(ROOT, "packages/core/src/admin/metricDefinitions.ts");
const TARGET = join(ROOT, "docs/admin/metrics.md");

const PERIOD_LABEL = {
  range: "Selected period",
  "all-time": "All time",
  "point-in-time": "Right now",
};

// esbuild is already a dependency (Vitest uses it); this avoids adding a
// TypeScript runner just to read one module.
async function loadDefinitions() {
  const esbuild = await import("esbuild");
  const dir = mkdtempSync(join(tmpdir(), "abonten-metrics-"));
  const out = join(dir, "metricDefinitions.mjs");
  await esbuild.build({
    entryPoints: [SOURCE],
    outfile: out,
    format: "esm",
    platform: "node",
    logLevel: "silent",
  });
  return import(pathToFileURL(out).href);
}

function render(definitions) {
  const groups = new Map();
  for (const def of definitions) {
    const group = def.key.split(".")[0];
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(def);
  }

  const GROUP_TITLES = {
    users: "People",
    organizers: "People",
    placeOwners: "People",
    events: "Catalogue",
    places: "Catalogue",
    tickets: "Tickets",
    money: "Money coming in",
    refunds: "Refunds",
    organizerMoney: "Organizer money",
    demo: "Who uses Abonten",
    attention: "Needs attention",
    health: "Needs attention",
    referrals: "Rewards › Referrals",
    rebates: "Rewards › Rebates",
    promoters: "Rewards › Promoters & loyalty",
    loyalty: "Rewards › Promoters & loyalty",
    search: "Discovery",
    recommendations: "Discovery",
    fieldOps: "Field Ops",
  };

  const sections = new Map();
  for (const [group, defs] of groups) {
    const title = GROUP_TITLES[group] ?? group;
    if (!sections.has(title)) sections.set(title, []);
    sections.get(title).push(...defs);
  }

  const body = [...sections.entries()]
    .map(([title, defs]) => {
      const entries = defs
        .map((def) =>
          [
            `### ${def.key}`,
            "",
            `**${def.label}** · ${PERIOD_LABEL[def.period]}`,
            "",
            def.definition,
            "",
            `Read from: \`${def.source}\``,
            ...(def.caveats?.length
              ? ["", "Watch out:", ...def.caveats.map((c) => `- ${c}`)]
              : []),
          ].join("\n"),
        )
        .join("\n\n");
      return `## ${title}\n\n${entries}`;
    })
    .join("\n\n");

  return `---
title: Admin › Metric definitions
purpose: What every figure in the admin console means, the period it covers and the rows it is read from.
audience: All admin roles
scope: /, /analytics, /finance, /rewards/*, /discovery, /field-ops/*
status: Approved
version: 1.1
lastReviewed: 2026-09-13
technicalOwner: Engineering (repository owner)
businessOwner: Abonten Hub founder
legalReviewRequired: no
complianceReviewRequired: no
---

<!-- Generated by scripts/gen-metric-glossary.mjs from
     packages/core/src/admin/metricDefinitions.ts. Edit that file, then run
     \`npm run docs:metrics\`. -->

# Admin › Metric definitions

The console shows the same wording beside each figure, behind its ⓘ. If a number here disagrees with a number elsewhere in Abonten, the definition below says which question each one answers.

${body}
`;
}

const module_ = await loadDefinitions();
const definitions = module_.metricKeys().map(module_.metricDefinition);
const next = render(definitions);

const check = process.argv.includes("--check");
if (check) {
  const current = readFileSync(TARGET, "utf8");
  if (current !== next) {
    console.error(
      "docs/admin/metrics.md is out of date. Run: npm run docs:metrics",
    );
    process.exit(1);
  }
  console.log("docs/admin/metrics.md is up to date.");
} else {
  writeFileSync(TARGET, next);
  console.log(`Wrote ${TARGET}`);
}
